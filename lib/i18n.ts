export function t(locale: Locale, key: DictKey, vars?: Record<string, string>): string {
  let str = dictionaries[locale]?.[key] ?? dictionaries.ru[key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      str = str.replace(`{${name}}`, value);
    }
  }
  return str;
}
